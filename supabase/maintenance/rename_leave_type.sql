-- 改假別名稱
--
--
-- 為什麼要用 SQL 改
--
-- 網站上目前沒有可以改假別「中文名稱」的地方：
--   · 管理後台 → 假期類型        只能改額度
--   · 管理後台 → 假別英文名稱    只能改 name_en（英文名）
-- 所以中文名稱只能從這裡改。
--
--
-- 改名安全嗎？
--
-- 安全。程式辨識假別靠的是旗標不是名字：
--   · 特休  看 leave_types.is_annual
--   · WFH   看 leave_types.is_wfh
-- 所以改名不會讓特休額度歸零，也不會讓 WFH 在 Slack 公告裡跑錯分組。
-- 已經送出的假單是用 leave_type_id 指過來的，改名之後那些假單會直接顯示
-- 新名稱，不需要（也不應該）另外去改。
--
-- 唯一要記得的是：中文名改了，英文名（name_en）不會跟著改。兩個都要改。
--
--
-- ── 用法 ───────────────────────────────────────────────────────────
-- 改下面 update 的 set 與 where 兩行，整段貼進 Supabase SQL Editor 執行。
-- 最後那段 select 會印出改完的結果讓你確認。
--
-- ⚠️ SQL Editor 只會顯示「最後一段」的結果，所以查詢一定要放在最後，
--    不要放中間 —— 放中間的話你會看不到它，以為沒跑到。
-- ───────────────────────────────────────────────────────────────────


-- 例：把「補休」改成 WFH（中文與英文一起改）
--
-- 這裡刻意用 where is_wfh = true 而不是 where name = '補休'：
-- 它剛好順便驗證了旗標有沒有標對 —— 如果 migration 沒標到，這句會改到
-- 0 列，最後的查詢就會看到 is_wfh 全都是 false，一眼就知道問題在哪。
update public.leave_types
   set name = 'WFH',
       name_en = 'WFH'
 where is_wfh = true;


-- 確認結果
select name       as 名稱,
       name_en    as 英文名稱,
       is_annual  as 是特休,
       is_wfh     as 是WFH,
       is_active  as 啟用中
  from public.leave_types
 order by name;

