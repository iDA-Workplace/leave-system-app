--
--   1. 上面的查詢裡，該是 WFH 的那一列 is_wfh 要是 true。
--      如果是 false，代表旗標沒標到，改名也沒發生 —— 先補旗標：
--        update public.leave_types set is_wfh = true where name = '<舊名稱>';
--      然後重跑這個檔案。
--
--   2. 一個假別不該同時是特休又是 WFH（特休是請假、WFH 不是請假）：
--        select name from public.leave_types where is_annual and is_wfh;
--      應該查不到任何一列。
--
