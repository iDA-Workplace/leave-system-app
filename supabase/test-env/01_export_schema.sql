-- ============================================================================
-- 在「正式」專案的 SQL Editor 執行：產生一份「只有結構、沒有任何資料」的建置腳本
-- ============================================================================
--
-- ✅ 這支只有 SELECT，不會改動正式資料庫的任何東西。
-- ✅ 輸出的內容「不含任何一筆資料」：沒有同仁帳號、假單、考核……只有
--    資料表長什麼樣子、函式、權限規則（RLS）、觸發器、檔案儲存桶的設定。
-- ❌ 刻意不包含：
--    - 排程（cron）：正式專案的排程會打正式的網址，複製過去會讓測試環境
--      去觸發正式的 Slack 通知。測試環境需要的排程另外在 README 裡設。
--    - 按摩預約（massage_*）：正式專案還沒有，而且測試環境之後會直接
--      執行 migrations/20261019_massage_booking.sql。
--    - Edge Functions 與 Secrets：那些不在資料庫裡，README 有另外的步驟。
--
-- 用法：整份貼進 SQL Editor → Run → 結果只有一格 → 點那一格、複製全部內容
-- → 到「測試」專案的 SQL Editor 貼上執行。

with
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p')
     and c.relname not like 'massage\_%'
     and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
fn as (
  select p.oid, p.proname, p.proacl,
         pg_get_function_identity_arguments(p.oid) as args
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f', 'p')
     and p.proname not like 'massage\_%' and p.proname <> 'is_massage_manager'
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
vw as (
  select c.oid, c.relname, c.relkind, c.reloptions
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('v', 'm')
     and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
-- 一行一個指令；ord 決定執行順序
stmts(ord, sub, stmt) as (
  -- 0. 函式內容先不檢查（函式之間、函式與資料表之間的先後順序就不用管）
  select 0, '', 'set check_function_bodies = off;'

  -- 1. 擴充套件
  union all
  select 1, e.extname,
         format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
   where e.extname <> 'plpgsql'

  -- 2. 自訂型別（enum）
  union all
  select 2, t.typname,
         format('create type public.%I as enum (%s);', t.typname,
                (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
                   from pg_enum e where e.enumtypid = t.oid))
    from pg_type t join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' and t.typtype = 'e'

  -- 3. 序號（identity 欄位自己會建，這裡只建獨立的）
  union all
  select 3, c.relname, format('create sequence if not exists public.%I;', c.relname)
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'S'
     and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('i', 'e'))

  -- 4. 資料表（預設值等函式建好之後再補，因為預設值可能會呼叫函式）
  union all
  select 4, t.relname,
         format('create table public.%I (%s);', t.relname,
                coalesce((
                  select string_agg(
                           format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
                           || case when a.attgenerated = 's'
                                   then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
                                   else '' end
                           || case a.attidentity when 'a' then ' generated always as identity'
                                                 when 'd' then ' generated by default as identity'
                                                 else '' end
                           || case when a.attnotnull and a.attidentity = '' then ' not null' else '' end,
                           ', ' order by a.attnum)
                    from pg_attribute a
                    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
                   where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped), ''))
    from tbl t

  -- 5. 函式
  union all
  select 5, f.proname || '(' || f.args || ')', pg_get_functiondef(f.oid) || ';'
    from fn f

  -- 6. 欄位預設值
  union all
  select 6, t.relname || '.' || a.attname,
         format('alter table public.%I alter column %I set default %s;', t.relname, a.attname,
                pg_get_expr(ad.adbin, ad.adrelid))
    from tbl t
    join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
   where a.attgenerated = ''

  -- 7. 主鍵、唯一、檢查條件（外鍵最後才加，見 9）
  union all
  select 7, t.relname || '.' || lpad(case co.contype when 'p' then '0' else '1' end, 1) || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
    from tbl t join pg_constraint co on co.conrelid = t.oid
   where co.contype in ('p', 'u', 'c', 'x')

  -- 8. 其他索引（不是主鍵／唯一條件自動建的那種）
  union all
  select 8, i.relname, pg_get_indexdef(i.oid) || ';'
    from tbl t
    join pg_index x on x.indrelid = t.oid
    join pg_class i on i.oid = x.indexrelid
   where not exists (select 1 from pg_constraint co where co.conindid = i.oid and co.conrelid = t.oid)

  -- 9. 外鍵
  union all
  select 9, t.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
    from tbl t join pg_constraint co on co.conrelid = t.oid
   where co.contype = 'f'

  -- 10. 檢視表（照建立順序）
  union all
  select 10, lpad(v.oid::text, 12, '0'),
         case v.relkind
           when 'v' then format('create or replace view public.%I%s as %s', v.relname,
                                case when v.reloptions is not null
                                     then ' with (' || array_to_string(v.reloptions, ', ') || ')' else '' end,
                                pg_get_viewdef(v.oid))
           else format('create materialized view public.%I as %s', v.relname,
                       rtrim(pg_get_viewdef(v.oid), ';')) || ' with no data;'
         end
    from vw v

  -- 11. 觸發器（public 的資料表，以及 auth.users 上呼叫 public 函式的）
  union all
  select 11, c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
    from pg_trigger tg
    join pg_class c on c.oid = tg.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_proc p on p.oid = tg.tgfoid
    join pg_namespace pn on pn.oid = p.pronamespace
   where not tg.tgisinternal
     and ((n.nspname = 'public' and c.oid in (select oid from tbl))
          or (n.nspname = 'auth' and pn.nspname = 'public'))

  -- 12. 開啟 RLS
  union all
  select 12, t.relname,
         format('alter table public.%I enable row level security;', t.relname)
         || case when t.relforcerowsecurity
                 then format(' alter table public.%I force row level security;', t.relname) else '' end
    from tbl t where t.relrowsecurity

  -- 13. RLS 規則（public 的資料表，以及 storage.objects 的檔案權限）
  union all
  select 13, n.nspname || '.' || c.relname || '.' || po.polname,
         format('create policy %I on %I.%I as %s for %s to %s%s%s;',
                po.polname, n.nspname, c.relname,
                case when po.polpermissive then 'permissive' else 'restrictive' end,
                case po.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update'
                               when 'd' then 'delete' else 'all' end,
                case when po.polroles = '{0}'::oid[] then 'public'
                     else (select string_agg(quote_ident(r.rolname), ', ') from pg_roles r where r.oid = any(po.polroles)) end,
                case when po.polqual is not null then ' using (' || pg_get_expr(po.polqual, po.polrelid) || ')' else '' end,
                case when po.polwithcheck is not null then ' with check (' || pg_get_expr(po.polwithcheck, po.polrelid) || ')' else '' end)
    from pg_policy po
    join pg_class c on c.oid = po.polrelid
    join pg_namespace n on n.oid = c.relnamespace
   where (n.nspname = 'public' and c.oid in (select oid from tbl))
      or (n.nspname = 'storage' and c.relname = 'objects')

  -- 14. 資料表／檢視表的權限：先收回 Supabase 預設給的，再照正式專案的設定給
  union all
  select 14, c.relname,
         format('revoke all on public.%I from anon, authenticated;', c.relname)
         || coalesce((
              select string_agg(format(' grant %s on public.%I to %I;', g.privs, c.relname, g.rolname), '')
                from (select r.rolname, string_agg(a.privilege_type, ', ') as privs
                        from aclexplode(c.relacl) a join pg_roles r on r.oid = a.grantee
                       where r.rolname in ('anon', 'authenticated', 'service_role')
                       group by r.rolname) g), '')
    from pg_class c
   where c.oid in (select oid from tbl union all select oid from vw) and c.relacl is not null

  -- 15. 函式的執行權限（沒有特別設定過的就維持預設，不輸出）
  union all
  select 15, f.proname || '(' || f.args || ')',
         format('revoke all on function public.%I(%s) from public, anon, authenticated;', f.proname, f.args)
         || coalesce((
              select string_agg(format(' grant execute on function public.%I(%s) to %s;', f.proname, f.args,
                                       case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), '')
                from aclexplode(f.proacl) a left join pg_roles r on r.oid = a.grantee
               where a.privilege_type = 'EXECUTE'
                 and (a.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))), '')
    from fn f where f.proacl is not null

  -- 16. 檔案儲存桶的設定（只有桶子本身，不含任何檔案）
  union all
  select 16, b.id,
         format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) on conflict (id) do nothing;',
                b.id, b.name, b.public,
                coalesce(b.file_size_limit::text, 'null'),
                coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
    from storage.buckets b

  -- 17. 即時更新（Realtime）訂閱的資料表
  union all
  select 17, pt.tablename,
         format('alter publication supabase_realtime add table public.%I;', pt.tablename)
    from pg_publication_tables pt
   where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
     and pt.tablename not like 'massage\_%'

  -- 18. 說明文字（資料表、欄位、函式上的 comment）
  union all
  select 18, t.relname || '.' || d.objsubid,
         case when d.objsubid = 0
              then format('comment on table public.%I is %L;', t.relname, d.description)
              else format('comment on column public.%I.%I is %L;', t.relname,
                          (select a.attname from pg_attribute a where a.attrelid = t.oid and a.attnum = d.objsubid),
                          d.description) end
    from tbl t join pg_description d on d.objoid = t.oid and d.classoid = 'pg_class'::regclass
  union all
  select 18, f.proname || '(' || f.args || ')',
         format('comment on function public.%I(%s) is %L;', f.proname, f.args, d.description)
    from fn f join pg_description d on d.objoid = f.oid and d.classoid = 'pg_proc'::regclass
)
select string_agg(stmt, E'\n\n' order by ord, sub) as "複製這一格的全部內容"
  from stmts;
